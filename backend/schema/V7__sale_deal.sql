create table sale_deal (
    id bigint primary key auto_increment comment "거래 ID. auto_increment이며 재수집하면 다시 발급",
    sigungu_code char(5) not null comment "시군구코드 (sggCd). 5자리",
    legal_dong_name varchar(50) not null comment "법정동명 (umdNm)",
    lot_number varchar(20) not null comment "지번 원본 값 (jibun). N, N-M이 아닌 값도 있음",
    house_name varchar(100) comment "단지명 (mhouseNm). 값이 없으면 null",
    build_year smallint comment "건축연도 (buildYear). 값이 없으면 null",
    exclusive_area decimal(10, 4) not null comment "전용면적 (excluUseAr). 단위 ㎡",
    floor smallint comment "층 (floor). 지하 N층은 -N, 값이 없으면 null",
    deal_date date not null comment "계약일 (dealYear, dealMonth, dealDay)",
    deal_amount int not null comment "거래금액 (dealAmount). 단위 만원",
    cancellation_type char(1) comment "해제 여부 (cdealType). 해제된 거래는 O, 해제되지 않은 거래는 null",
    cancellation_date date comment "해제 사유 발생일 (cdealDay). 원본 YY.MM.DD를 20YY-MM-DD로 변환, 값이 없으면 null",
    building_parcel_id bigint comment "필지 ID. 매칭에 실패하면 null",
    match_status varchar(30) not null comment "매칭 상태. CONFIRMED, ESTIMATED, PREVIOUS, FAILED",
    created_at datetime not null default current_timestamp comment "생성 시각",
    updated_at datetime not null default current_timestamp on update current_timestamp comment "수정 시각",
    constraint fk_sale_deal_building_parcel foreign key (building_parcel_id) references building_parcel (id),
    constraint ck_sale_deal_match_status check ((match_status = 'FAILED') = (building_parcel_id is null)),
    index idx_sale_deal_sigungu_code_deal_date (sigungu_code, deal_date),
    index idx_sale_deal_building_parcel_id_deal_date (building_parcel_id, deal_date)
) comment "매매 거래";
