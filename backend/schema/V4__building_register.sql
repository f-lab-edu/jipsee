create table building_register (
    id bigint primary key auto_increment comment "동 ID",
    building_parcel_id bigint not null comment "필지 ID",
    management_register_key varchar(22) not null comment "관리 건축물대장 PK (mgmBldrgstPk)",
    lot_address varchar(200) not null comment "지번주소 (platPlc)",
    road_address varchar(200) comment "도로명주소 (newPlatPlc). 값이 없으면 null",
    name varchar(200) comment "건물명 (bldNm). 값이 없으면 null",
    dong_name varchar(100) comment "건축물 동 명칭 (dongNm). 값이 없으면 null",
    main_annex_type_code char(1) not null comment "주/부속 건축물 구분 (mainAtchGbCd). 0: 주건축물, 1: 부속건축물",
    use_approval_date char(8) comment "사용승인일 (useAprDay). YYYYMMDD. 연도만 있거나 일이 00인 값이 원본 그대로 들어갈 수 있음. 값이 없으면 null",
    household_count int comment "세대 수 (hhldCnt). 값이 없으면 null",
    above_ground_floor_count int comment "지상 층수 (grndFlrCnt). 값이 없으면 null",
    underground_floor_count int comment "지하 층수 (ugrndFlrCnt). 값이 없으면 null",
    passenger_elevator_count int comment "승용 승강기 수 (rideUseElvtCnt). 값이 없으면 null",
    structure_name varchar(50) comment "구조 코드명 (strctCdNm). 값이 없으면 null",
    earthquake_design_applied char(1) comment "내진설계 적용 여부 (rserthqkDsgnApplyYn). 0: 적용하지 않음, 1: 적용함. 값이 없으면 null",
    total_floor_area decimal(14, 4) comment "연면적 (totArea). 단위 ㎡. 값이 없으면 null",
    etc_purpose varchar(100) comment "기타용도 (etcPurps). 값이 없으면 null",
    indoor_mechanical_parking_count int comment "옥내 기계식 주차 대수 (indrMechUtcnt). 값이 없으면 null",
    outdoor_mechanical_parking_count int comment "옥외 기계식 주차 대수 (oudrMechUtcnt). 값이 없으면 null",
    indoor_self_propelled_parking_count int comment "옥내 자주식 주차 대수 (indrAutoUtcnt). 값이 없으면 null",
    outdoor_self_propelled_parking_count int comment "옥외 자주식 주차 대수 (oudrAutoUtcnt). 값이 없으면 null",
    created_at datetime not null default current_timestamp comment "생성 시각",
    updated_at datetime not null default current_timestamp on update current_timestamp comment "수정 시각",
    constraint uk_building_register_management_register_key unique (management_register_key),
    constraint fk_building_register_building_parcel foreign key (building_parcel_id) references building_parcel (id),
    fulltext index ft_building_register_search (name, lot_address, road_address) with parser ngram
) comment "건축물대장 표제부 동";